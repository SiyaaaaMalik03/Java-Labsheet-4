/*
Hybrid Inheritance: Concept Only

Hybrid inheritance is a combination of two or more types
of inheritance.

Example structure:

        Person
           |
       Employee
       /       \
   Doctor   Pharmacist

Person → Employee represents multilevel inheritance.

Employee → Doctor and Employee → Pharmacist represent
hierarchical inheritance.

This combined structure is called hybrid inheritance.

As instructed in the question, multiple class inheritance
is not implemented here.
*/